class MathHelper{
    static add(a,b){
        return a+b
    }
    static subtract(a,b){
        return a-b
    }
    static divide(a,b){
        return a/b
    }
    static multiply(a,b){
        return a*b
    }
}
console.log(MathHelper.add(10,5))
console.log(MathHelper.subtract(10,5))
console.log(MathHelper.divide(10,5))
console.log(MathHelper.multiply(10,5))